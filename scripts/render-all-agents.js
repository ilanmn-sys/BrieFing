#!/usr/bin/env node
// Pre-renders every agent's cloud instructions to agents/<id>/rendered.md.
//   node scripts/render-all-agents.js
// Why: cloud Routine sessions run in auto mode, and the classifier blocks executing
// `node scripts/render-agent.js` from a freshly cloned repo as "code from an external
// source" (seen 04.11 on weekly-linkedin-post-proposal). Routines therefore only READ
// the committed rendered.md. Re-run this after editing any agent prompt, tool list,
// schedule.json cloud mode or config.json, and commit the result.
const fs = require('fs');
const path = require('path');
const agents = require('../server/agents');
const { renderFor } = require('./render-agent');

const DATE_LINE = /^Today is \d{4}-\d{2}-\d{2} \(read from the system clock\)\./;
const CLOCK = 'Read the system clock first: today\'s date and weekday come from it, never from this file or from board data.';

let n = 0;
for (const name of fs.readdirSync(agents.agentsDir())) {
  const dir = path.join(agents.agentsDir(), name);
  if (!fs.existsSync(path.join(dir, 'schedule.json'))) continue;
  const { mode, prompt } = renderFor(name);
  const body = prompt.replace(DATE_LINE, CLOCK);
  const header = `<!-- Generated by scripts/render-all-agents.js. Do not edit by hand. Mode: ${mode.toUpperCase()} -->\n`;
  fs.writeFileSync(path.join(dir, 'rendered.md'), header + body + '\n');
  n++;
}
console.log(`rendered ${n} agents`);
